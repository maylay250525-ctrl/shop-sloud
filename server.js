// Email OTP for registration (Gmail, free, 500/day). A customer who enters
// an email gets a 6-digit code by email and must type it in before the
// account is created; customers without an email register with a password
// exactly as before. Codes live in server memory only — a restart clears
// pending codes (the customer just taps resend).
//
// Protections, as the user chose: 60s resend cooldown (with a countdown on
// the button), max 5 codes per email per day ("ဒီနေ့ များသွားပြီ, မနက်ဖြန်မှ
// ပြန်တောင်းပါ"), code valid 5 minutes, 5 wrong tries invalidates the code.
// Plus a per-IP guard (20 code requests/hour) so one device cannot burn
// the daily Gmail quota for everyone.
// ---------------------------------------------------------------------------
const OTP_CODE_MS = (Number(process.env.OTP_CODE_MINS || 5) || 5) * 60 * 1000;
const OTP_RESEND_MS = (Number(process.env.OTP_RESEND_SECS || 60) || 60) * 1000;
const OTP_MAX_PER_DAY = Number(process.env.OTP_MAX_PER_DAY || 5) || 5;
const OTP_MAX_TRIES = 5;
const OTP_TOKEN_MS = 10 * 60 * 1000; // verified-email token, for registration
const OTP_IP_MAX_PER_HOUR = 20;
const otpCodes = new Map(); // email -> { code, expiresAt, attempts, sentCount, dayKey, lastSentAt }
const otpIpHits = new Map(); // ip -> { count, hourKey }
function otpDayKey() { return new Date(Date.now() + 6.5 * 3600 * 1000).toISOString().slice(0, 10); } // Rangoon date
function otpHourKey() { return new Date().toISOString().slice(0, 13); }
setInterval(() => {
  const now = Date.now();
  for (const [email, rec] of otpCodes) if (now > rec.expiresAt) otpCodes.delete(email);
  for (const [ip, hit] of otpIpHits) if (hit.hourKey !== otpHourKey()) otpIpHits.delete(ip);
}, 60 * 1000).unref();

let mailTransport = null;
function getMailer() {
  if (mailTransport) return mailTransport;
  if (process.env.SMTP_HOST && process.env.SMTP_USER && process.env.SMTP_PASS) {
    mailTransport = nodemailer.createTransport({
      host: process.env.SMTP_HOST, port: Number(process.env.SMTP_PORT || 587),
      secure: Number(process.env.SMTP_PORT) === 465,
      auth: { user: process.env.SMTP_USER, pass: process.env.SMTP_PASS },
    });
  } else if (GMAIL_USER && GMAIL_APP_PASSWORD) {
    mailTransport = nodemailer.createTransport({
      service: 'gmail', auth: { user: GMAIL_USER, pass: GMAIL_APP_PASSWORD },
    });
  }
  return mailTransport;
}
function mailFrom() { return GMAIL_USER || process.env.SMTP_USER || ''; }

// Short-lived HMAC token proving an email passed OTP verification. The
// register endpoint requires it when an email is given, so the client
// cannot claim "verified" without the code.
function signOtpToken(email) {
  const payload = { email, exp: Date.now() + OTP_TOKEN_MS };
  const data = Buffer.from(JSON.stringify(payload)).toString('base64url');
  const sig = crypto.createHmac('sha256', AUTH_SECRET).update(data).digest('base64url');
  return data + '.' + sig;
}
function verifyOtpToken(token, email) {
  if (!token || typeof token !== 'string') return false;
  const parts = token.split('.');
  if (parts.length !== 2) return false;
  const [data, sig] = parts;
  const expect = crypto.createHmac('sha256', AUTH_SECRET).update(data).digest('base64url');
  let sigBuf, expBuf;
  try { sigBuf = Buffer.from(sig, 'base64url'); expBuf = Buffer.from(expect, 'base64url'); } catch (e) { return false; }
  if (sigBuf.length !== expBuf.length || !crypto.timingSafeEqual(sigBuf, expBuf)) return false;
  let payload;
  try { payload = JSON.parse(Buffer.from(data, 'base64url').toString('utf8')); } catch (e) { return false; }
  return !!payload && payload.email === email && payload.exp > Date.now();
}
const EMAIL_RE = /^[^\s@]+@[^\s@]+\.[^\s@]+$/;

// Send a 6-digit code to an email address (registration step 1).
app.post('/api/auth/request-otp', ah(async (req, res) => {
  const email = String((req.body || {}).email || '').trim().toLowerCase();
  if (!EMAIL_RE.test(email)) return res.status(400).json({ error: 'invalid email' });
  const phone = String((req.body || {}).phone || '').trim();
  if (phone && await store.getUserByPhone(phone)) return res.status(409).json({ error: 'phone already registered' });
  const mailer = getMailer();
  if (!mailer) return res.status(503).json({ error: 'email_not_configured' });
  const now = Date.now();
  const dayKey = otpDayKey();
  const rec = otpCodes.get(email);
  if (rec && rec.dayKey === dayKey && rec.sentCount >= OTP_MAX_PER_DAY) {
    return res.status(429).json({ error: 'daily_limit' });
  }
  if (rec && now - rec.lastSentAt < OTP_RESEND_MS) {
    return res.status(429).json({ error: 'cooldown', retryAfter: Math.ceil((OTP_RESEND_MS - (now - rec.lastSentAt)) / 1000) });
  }
  const ip = clientIp(req);
  const hit = otpIpHits.get(ip);
  if (hit && hit.hourKey === otpHourKey() && hit.count >= OTP_IP_MAX_PER_HOUR) {
    return res.status(429).json({ error: 'too_many_requests' });
  }
  const code = String(Math.floor(100000 + Math.random() * 900000));
  otpCodes.set(email, {
    code, expiresAt: now + OTP_CODE_MS, attempts: 0,
    sentCount: (rec && rec.dayKey === dayKey) ? rec.sentCount + 1 : 1,
    dayKey, lastSentAt: now,
  });
  otpIpHits.set(ip, { count: (hit && hit.hourKey === otpHourKey()) ? hit.count + 1 : 1, hourKey: otpHourKey() });
  try {
    await mailer.sendMail({
      from: mailFrom(), to: email,
      subject: 'ဈေးဆိုင် — အကောင့်ဖွင့်ဖို့ code',
      text: 'မင်္ဂလာပါ။\n\nဈေးဆိုင် အကောင့်ဖွင့်ဖို့ code: ' + code + '\n\nဒီ code က ၅ မိနစ်ပဲ အကျိုးရှိတယ်။ သင်ကိုယ်တိုင် မတောင်းဘူးဆိုရင် ဒီမေးလ်ကို လျစ်လျူရှုပါ။',
    });
  } catch (e) {
    return res.status(500).json({ error: 'send_failed' });
  }
  res.json({ ok: true, expiresIn: Math.round(OTP_CODE_MS / 1000) });
}));

// Verify a code (registration step 2). Returns a one-time token that the
// register call must present. Wrong 5 times invalidates the code.
app.post('/api/auth/verify-otp', ah(async (req, res) => {
  const email = String((req.body || {}).email || '').trim().toLowerCase();
  const code = String((req.body || {}).code || '').trim();
  const rec = otpCodes.get(email);
  if (!rec) return res.status(400).json({ error: 'no_code' });
  if (Date.now() > rec.expiresAt) { otpCodes.delete(email); return res.status(400).json({ error: 'code_expired' }); }
  if (rec.code !== code) {
    rec.attempts += 1;
    if (rec.attempts >= OTP_MAX_TRIES) { otpCodes.delete(email); return res.status(400).json({ error: 'too_many_attempts' }); }
    return res.status(400).json({ error: 'wrong_code', triesLeft: OTP_MAX_TRIES - rec.attempts });
  }
  otpCodes.delete(email);
  res.json({ ok: true, otpToken: signOtpToken(email) });
}));

// ---------------------------------------------------------------------------
// Customer auth — password login, one account per phone, 48h sessions.
// Passwords are stored as scrypt hashes (salted); tokens are HMAC-signed
// (payload: user id + phone + name + expiry) and checked on every call.
// ---------------------------------------------------------------------------
function hashPassword(password, salt) {
  return crypto.scryptSync(password, salt, 64).toString('hex');
}
function signToken(user) {
  const payload = { uid: user.id, phone: user.phone, name: user.name, exp: Date.now() + SESSION_MS };
  const data = Buffer.from(JSON.stringify(payload)).toString('base64url');
  const sig = crypto.createHmac('sha256', AUTH_SECRET).update(data).digest('base64url');
  return data + '.' + sig;
}
function verifyToken(token) {
  if (!token || typeof token !== 'string') return null;
  const parts = token.split('.');
  if (parts.length !== 2) return null;
  const [data, sig] = parts;
  const expect = crypto.createHmac('sha256', AUTH_SECRET).update(data).digest('base64url');
  const sigBuf = Buffer.from(sig, 'base64url');
  const expBuf = Buffer.from(expect, 'base64url');
  if (sigBuf.length !== expBuf.length || !crypto.timingSafeEqual(sigBuf, expBuf)) return null;
  let payload;
  try { payload = JSON.parse(Buffer.from(data, 'base64url').toString('utf8')); } catch (e) { return null; }
  if (!payload || !payload.uid || !payload.phone || !payload.exp || payload.exp < Date.now()) return null;
  return payload;
}
function requireAuth(req, res, next) {
  const h = req.headers['authorization'] || '';
  const token = h.startsWith('Bearer ') ? h.slice(7) : null;
  const payload = verifyToken(token);
  if (!payload) return res.status(401).json({ error: 'login required' });
  req.user = payload;
  next();
}

