// shop-cloud server: one Express app, one shared database.
// Shop and Admin both read/write the same store, so a shop top-up/order
// appears in Admin immediately and admin edits update the shop immediately.
//
// Storage:
//   * Default: JSON file store (data/db.json) — zero setup, local testing.
//   * If DATABASE_URL is set: Postgres (Neon / Supabase free tier) —
//     data survives Render restarts / spin-downs. See store.js.
// No native dependencies besides `pg` (only loaded when DATABASE_URL is set).
const express = require('express');
const crypto = require('crypto');
const path = require('path');
const { createStore } = require('./store');

const app = express();
app.use(express.json({ limit: '2mb' })); // product photos arrive as resized data URLs
app.use(express.static(path.join(__dirname, 'public')));

const PORT = process.env.PORT || 3000;
const ADMIN_PASSCODE = process.env.ADMIN_PASSCODE || 'admin123';
// Signs customer login tokens. On Render this is auto-generated by
// render.yaml (AUTH_SECRET, generateValue) — never commit a real value.
// Without it the fallback below applies (dev only: anyone who reads the
// public repo could forge tokens, so always set AUTH_SECRET in production).
const AUTH_SECRET = process.env.AUTH_SECRET || 'dev-only-secret';
if (!process.env.AUTH_SECRET) console.log('warning: AUTH_SECRET not set, using dev fallback — set a random AUTH_SECRET in Render Environment');
const SESSION_MS = 48 * 60 * 60 * 1000; // customer login lasts 48 hours

let store; // set in start() before listening

// Async-handler wrapper: forward errors to Express instead of hanging.
const ah = fn => (req, res, next) => Promise.resolve(fn(req, res, next)).catch(next);

function requireAdmin(req, res, next) {
  if (req.headers['x-admin-passcode'] !== ADMIN_PASSCODE) {
    return res.status(401).json({ error: 'unauthorized' });
  }
  next();
}

// ---------------------------------------------------------------------------
// Customer auth — password login, one account per phone, 48h sessions.
// Passwords are stored as scrypt hashes (salted); tokens are HMAC-signed
// (payload: user id + phone + name + expiry) and checked on every call.
// ---------------------------------------------------------------------------
function hashPassword(password, salt) {
  return crypto.scryptSync(password, salt, 64).toString('hex');
}
function signToken(user) {
  const payload = { uid: user.id, phone: user.phone, name: user.name, exp: Date.now() + SESSION_MS };
  const data = Buffer.from(JSON.stringify(payload)).toString('base64url');
  const sig = crypto.createHmac('sha256', AUTH_SECRET).update(data).digest('base64url');
  return data + '.' + sig;
}
function verifyToken(token) {
  if (!token || typeof token !== 'string') return null;
  const parts = token.split('.');
  if (parts.length !== 2) return null;
  const [data, sig] = parts;
  const expect = crypto.createHmac('sha256', AUTH_SECRET).update(data).digest('base64url');
  const sigBuf = Buffer.from(sig, 'base64url');
  const expBuf = Buffer.from(expect, 'base64url');
  if (sigBuf.length !== expBuf.length || !crypto.timingSafeEqual(sigBuf, expBuf)) return null;
  let payload;
  try { payload = JSON.parse(Buffer.from(data, 'base64url').toString('utf8')); } catch (e) { return null; }
  if (!payload || !payload.uid || !payload.phone || !payload.exp || payload.exp < Date.now()) return null;
  return payload;
}
function requireAuth(req, res, next) {
  const h = req.headers['authorization'] || '';
  const token = h.startsWith('Bearer ') ? h.slice(7) : null;
  const payload = verifyToken(token);
  if (!payload) return res.status(401).json({ error: 'login required' });
  req.user = payload;
  next();
}

