// Register: one account per phone number — a registered phone cannot
// register again (409). Wallet balance stays keyed by phone, so an existing
// wallet for that phone carries over to the new account automatically.
app.post('/api/auth/register', ah(async (req, res) => {
  const { name, phone, password, email, otpToken } = req.body || {};
  if (!name || !String(name).trim() || !phone || !String(phone).trim() ||
      !password || String(password).length < 4) {
    return res.status(400).json({ error: 'name, phone and password (min 4 chars) required' });
  }
  const cleanPhone = String(phone).trim();
  const cleanEmail = email ? String(email).trim().toLowerCase() : '';
  // Email is optional: without it, registration works exactly as before.
  // With it, the email must have passed OTP verification (otpToken proves
  // the code was typed in), otherwise anyone could claim any address.
  if (cleanEmail) {
    if (!EMAIL_RE.test(cleanEmail)) return res.status(400).json({ error: 'invalid email' });
    if (!verifyOtpToken(otpToken, cleanEmail)) return res.status(400).json({ error: 'email_verification_required' });
  }
  const existing = await store.getUserByPhone(cleanPhone);
  if (existing) return res.status(409).json({ error: 'phone already registered' });
  const salt = crypto.randomBytes(16).toString('hex');
  const user = {
    id: 'u' + Date.now().toString(36),
    name: String(name).trim(), phone: cleanPhone,
    email: cleanEmail, emailVerified: !!cleanEmail,
    passwordHash: hashPassword(String(password), salt), salt,
    createdAt: new Date().toISOString(),
  };
  await store.createUser(user);
  res.status(201).json({ token: signToken(user), user: { id: user.id, name: user.name, phone: user.phone, email: user.email } });
}));

// Google login ("Sign in with Google"). The client sends Google's signed
// ID token; the server verifies it against Google's keys (no client secret
// needed) and logs the customer in. Shop accounts are keyed by phone, and
// Google only proves an email, so:
//   - a user with this email exists → log in as them;
//   - no user with this email, but the given phone has an account → link
//     the email to that phone account (only if it has no other verified
//     email) and log in;
//   - neither exists → a phone is required; the client asks for it once,
//     then this call creates the account (phone + verified email) and logs
//     in. Google accounts get a random password hash they never use —
//     password login stays available via an Admin reset.
app.post('/api/auth/google', ah(async (req, res) => {
  const { credential, phone, name } = req.body || {};
  if (!GOOGLE_CLIENT_ID) return res.status(503).json({ error: 'google_not_configured' });
  if (!credential || typeof credential !== 'string') return res.status(400).json({ error: 'missing credential' });
  let payload;
  try {
    const client = new OAuth2Client(GOOGLE_CLIENT_ID);
    const ticket = await client.verifyIdToken({ idToken: credential, audience: GOOGLE_CLIENT_ID });
    payload = ticket.getPayload();
  } catch (e) {
    return res.status(401).json({ error: 'invalid google token' });
  }
  const email = String(payload.email || '').trim().toLowerCase();
  if (!payload.email_verified || !EMAIL_RE.test(email)) return res.status(401).json({ error: 'google email not verified' });
  const googleName = String(name || payload.name || '').trim();
  // Find an existing user by email (listUsers is the only email lookup).
  const users = await store.listUsers();
  let user = null;
  for (const u of users) {
    if ((u.email || '').toLowerCase() === email) { user = await store.getUserByPhone(u.phone); break; }
  }
  if (user) {
    return res.json({ token: signToken(user), user: { id: user.id, name: user.name, phone: user.phone, email: user.email || '' } });
  }
  const cleanPhone = phone ? String(phone).trim() : '';
  if (!cleanPhone) {
    return res.json({ needsPhone: true, email, name: googleName });
  }
  const byPhone = await store.getUserByPhone(cleanPhone);
  if (byPhone) {
    if (byPhone.email && byPhone.email.toLowerCase() !== email) {
      return res.status(409).json({ error: 'phone linked to another email' });
    }
    // Link this Google email to the existing phone account (email +
    // verified flag only — wallet, orders and chats are keyed by phone
    // and stay untouched).
    const linked = await store.updateUserEmail(cleanPhone, email);
    if (!linked) return res.status(500).json({ error: 'link failed' });
    return res.json({ token: signToken(linked), user: { id: linked.id, name: linked.name, phone: linked.phone, email: linked.email || '' } });
  }
  const salt = crypto.randomBytes(16).toString('hex');
  const randomPass = crypto.randomBytes(32).toString('hex');
  const fresh = {
    id: 'u' + Date.now().toString(36),
    name: googleName || email.split('@')[0], phone: cleanPhone,
    email, emailVerified: true,
    passwordHash: hashPassword(randomPass, salt), salt,
    createdAt: new Date().toISOString(),
  };
  await store.createUser(fresh);
  res.status(201).json({ token: signToken(fresh), user: { id: fresh.id, name: fresh.name, phone: fresh.phone, email: fresh.email } });
}));

// Login: returns a token valid for 48 hours.
